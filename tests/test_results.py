_CURRENT_DOCS = (
    "README.md",
    "CLAUDE.md",
    "docs/DEMO_SCRIPT.md",
    "docs/powerbi_setup.md",
    "docs/MANUAL_CHECKS.md",
    "docs/SYLLABUS_MAP.md",
    "docs/README.md",
)
_SUPERSEDED = (
    "361,860",
    "423 MB",
    "Star 454",
    "454/478/480/452",
    "0.7841",
    "0.7928",
    "61 passed",
    "10 source files",
)


@pytest.mark.parametrize("relative", _CURRENT_DOCS)
def test_current_documents_do_not_quote_superseded_numbers(relative: str) -> None:
    path = ROOT / relative
    if not path.exists():
        pytest.skip(f"{relative} does not exist")
    found = [s for s in _SUPERSEDED if s in _read(path)]
    assert not found, f"{relative} quotes superseded figures: {found}"


# --------------------------------------------------------------------------
# docs/SYLLABUS_MAP.md: every path it lists exists
# --------------------------------------------------------------------------


def test_syllabus_map_lists_only_existing_paths() -> None:
    path = ROOT / "docs" / "SYLLABUS_MAP.md"
    assert path.exists(), "docs/SYLLABUS_MAP.md is missing"
    text = _read(path)
    pattern = r"`((?:src|app|rules|docs|reports|scripts|sql|tests)/[^`\s]+)`"
    listed = set(re.findall(pattern, text))
    assert listed, "the syllabus map lists no paths"
    missing = []
    for item in sorted(listed):
        file_part, _, symbol = item.partition("::")
        if "*" in file_part:
            if not list(ROOT.glob(file_part)):
                missing.append(item)
        elif not (ROOT / file_part).exists():
            missing.append(item)
        elif symbol:
            source = _read(ROOT / file_part)
            if not re.search(rf"^(?:def|class) {re.escape(symbol)}\b", source, re.MULTILINE):
                missing.append(item)
    assert not missing, f"docs/SYLLABUS_MAP.md lists names that do not exist: {missing}"
