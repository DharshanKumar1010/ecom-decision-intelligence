"""Tests that the documents quote the project's real numbers.

`reports/RESULTS.md` is generated by `scripts/make_results.py` from the pipeline outputs. These
tests check that it is current, that the demo script's quoted figures agree with it, that the
threshold table in docs/knowledge_engineering.md equals rules/seller_rules.yaml, that current
documents carry no superseded number, and that every path listed in docs/SYLLABUS_MAP.md
exists. They skip when the pipeline outputs are absent.
"""

from __future__ import annotations

import importlib.util
import re
from pathlib import Path
from types import ModuleType

import pytest

from src import config
from src.expert import KnowledgeBase

ROOT = config.PROJECT_ROOT
RESULTS = config.REPORTS_DIR / "RESULTS.md"
_NEEDED = (
    config.PROCESSED_DATA_DIR / "SellerFacts.parquet",
    config.PROCESSED_DATA_DIR / "LatePredictions.parquet",
    config.MODELS_DIR / "registry.json",
    config.EXPORT_DATA_DIR / "FactOrderItems.csv",
    config.REPORTS_DIR / "oof_metrics.json",
)
needs_outputs = pytest.mark.skipif(
    not all(p.exists() for p in _NEEDED), reason="pipeline outputs not generated; run run_all.py"
)


def _make_results() -> ModuleType:
    path = ROOT / "scripts" / "make_results.py"
    spec = importlib.util.spec_from_file_location("make_results", path)
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _read(path: Path) -> str:
    return path.read_bytes().decode("utf-8").replace("\r\n", "\n")


@needs_outputs
def test_results_md_is_current() -> None:
    expected = _make_results().build_results()
    assert RESULTS.exists(), "reports/RESULTS.md is missing; run python scripts/make_results.py"
    assert _read(RESULTS) == expected, (
        "reports/RESULTS.md is out of date; run python scripts/make_results.py"
    )


@needs_outputs
def test_make_results_check_mode_agrees() -> None:
    assert _make_results().main(["--check"]) == 0


# --------------------------------------------------------------------------
# Figures quoted in the demo script must equal the ones in RESULTS.md
# --------------------------------------------------------------------------


def _demo_text() -> str:
    text = _read(ROOT / "docs" / "DEMO_SCRIPT.md")
    return re.sub(r"\s+", " ", re.sub(r"^> ?", "", text, flags=re.MULTILINE))


def _one(pattern: str, text: str, what: str) -> str:
    match = re.search(pattern, text)
    assert match, f"cannot find {what} using {pattern!r}"
    return match.group(1)


def _two(four_decimals: str) -> str:
    return f"{float(four_decimals):.2f}"


def _model_row(results: str, name: str) -> tuple[str, str]:
    """(test AUC, out-of-fold AUC) of a model from the RESULTS.md model table."""
    pattern = rf"\| `{name}` \| [^|]+ \| (0\.\d{{4}}) \| (0\.\d{{4}}) \|"
    match = re.search(pattern, results)
    assert match, name
    return match.group(1), match.group(2)


@needs_outputs
def test_demo_script_figures_match_results() -> None:
    demo, res = _demo_text(), _read(RESULTS)
    rf_test, rf_oof = _model_row(res, "random_forest")
    dt_test, _ = _model_row(res, "decision_tree")
    lr_test, _ = _model_row(res, "logistic_regression")

    # Question 1: held-out AUCs to two decimals, and the five-fold figure to four.
    assert _one(r"the linear model scores (0\.\d\d)", demo, "linear AUC") == _two(lr_test)
    assert _one(r"the decision tree (0\.\d\d)", demo, "tree AUC") == _two(dt_test)
    assert _one(r"and the forest (0\.\d\d) \(", demo, "forest AUC") == _two(rf_test)
    assert _one(r"\((0\.\d{4}) averaged over five", demo, "forest OOF") == rf_oof

    # Question 3: recall and precision of the primary model, and the base late rate.
    assert _one(r"recall (0\.\d\d)", demo, "recall") == _one(r"recall (0\.\d\d)\)", res, "recall")
    assert _one(r"precision (0\.\d\d)", demo, "precision") == _one(
        r"precision (0\.\d\d)\.", res, "precision"
    )
    assert _one(r"where (\d\.\d)% of items are late", demo, "late rate") == _one(
        r"Base rate of late items (\d\.\d)\d%", res, "base rate"
    )

    # Hidden gems and their evidence tiers.
    assert _one(r"there are (\d+)\.", demo, "gem count") == _one(
        r"\| Hidden Gem \| (\d+) \|", res, "gems"
    )
    assert _one(r"Only (\d+) have 15 or more", demo, "stronger") == _one(
        r"Hidden gems by evidence: (\d+) with", res, "stronger"
    )
    assert _one(r"the other (\d+) are an Early signal", demo, "early") == _one(
        r"\(stronger evidence\), (\d+) with fewer", res, "early"
    )

    # Seller-level correlation of risk with the actual late rate.
    assert _one(r"the correlation is (0\.\d\d) \(", demo, "corr all") == _one(
        r"late rate: (0\.\d\d) over all", res, "corr all"
    )
    assert _one(r"\((0\.\d\d) for sellers with 5 or more", demo, "corr 5+") == _one(
        r"over all [\d,]+ sellers, (0\.\d\d) over", res, "corr 5+"
    )

    # Question 11, forward-looking check: forest, tree, linear with and without the calendar.
    row = r"\| {} \| (0\.\d{{4}}) \| (0\.\d{{4}}) \| (0\.\d{{4}}) \|"
    with_cal = re.search(row.format("all 12 features"), res)
    without = re.search(row.format(r"without `order_month` and `day_of_week`"), res)
    assert with_cal and without
    lr_w, dt_w, rf_w = (_two(g) for g in with_cal.groups())
    lr_o, dt_o, rf_o = (_two(g) for g in without.groups())
    assert f"forest {rf_w}, tree {dt_w}, linear model {lr_w}" in demo
    assert f"fall to {rf_o}, {dt_o} and {lr_o}" in demo

    # Consistency ratio and the saved forest's size.
    cr = float(_one(r"consistency ratio (0\.\d{4})", res, "CR"))
    assert _one(r"consistency ratio (0\.\d\d\d)", demo, "CR") == f"{cr:.3f}"
    size_mb = float(_one(r"Saved forest on disk: ([\d.]+) MB", res, "forest size"))
    assert f"about {size_mb:.0f} MB" in demo


# --------------------------------------------------------------------------
# Thresholds in docs/knowledge_engineering.md section 6 equal the rule file
# --------------------------------------------------------------------------


def test_knowledge_engineering_threshold_table_equals_the_rule_file() -> None:
    mr = _make_results()
    kb = KnowledgeBase.from_yaml(config.RULES_DIR / "seller_rules.yaml")
    doc = _read(ROOT / "docs" / "knowledge_engineering.md")
    section = doc.split("## 6. Rule thresholds", 1)[1].split("**Priority ladder**", 1)[0]
    in_doc = {
        m.group(1): m.group(2)
        for m in re.finditer(r"^\| (R\d\d) \w+ \| `([^`]+)` \|", section, re.MULTILINE)
    }
    in_yaml = {rule.id: mr.rule_condition_text(rule) for rule in kb.rules}
    assert in_doc == in_yaml


